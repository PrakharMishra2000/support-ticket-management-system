CREATE TABLE tickets (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title         VARCHAR(200)  NOT NULL,
  description   VARCHAR(8000) NOT NULL,
  status        ticket_status   NOT NULL DEFAULT 'OPEN',
  priority      ticket_priority NOT NULL DEFAULT 'MEDIUM',
  category      VARCHAR(64),
  assignee_id   BIGINT,
  reporter_id   BIGINT        NOT NULL,
  created_at    TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_tickets_title_len CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
  CONSTRAINT chk_tickets_description_len CHECK (char_length(btrim(description)) BETWEEN 1 AND 8000),
  CONSTRAINT chk_tickets_category CHECK (
    category IS NULL OR category ~ '^[A-Za-z0-9 _-]{1,64}$'
  ),
  CONSTRAINT chk_tickets_assignee_id CHECK (assignee_id IS NULL OR assignee_id > 0),
  CONSTRAINT chk_tickets_reporter_id CHECK (reporter_id > 0)
);

CREATE INDEX idx_tickets_status ON tickets (status);
CREATE INDEX idx_tickets_priority ON tickets (priority);
CREATE INDEX idx_tickets_assignee_id ON tickets (assignee_id);
CREATE INDEX idx_tickets_reporter_id ON tickets (reporter_id);
CREATE INDEX idx_tickets_created_at ON tickets (created_at DESC);
CREATE INDEX idx_tickets_category ON tickets (lower(category));
